# Summarize optimizer/convergence diagnostics from an lmer model.
# Singularity and convergence are reported separately because they represent
# different model-quality issues.
model_convergence_status <- function(model) {

  optimizer_code <- model@optinfo$conv$opt
  convergence_messages <- model@optinfo$conv$lme4$messages

  optimizer_ok <- is.null(optimizer_code) ||
    all(unlist(optimizer_code, use.names = FALSE) == 0)

  messages_ok <- is.null(convergence_messages) ||
    length(convergence_messages) == 0

  list(
    ok = isTRUE(optimizer_ok) && isTRUE(messages_ok),
    optimizer_code = if (is.null(optimizer_code)) {
      NA_character_
    } else {
      paste(as.character(unlist(optimizer_code, use.names = FALSE)), collapse = "; ")
    },
    message = if (is.null(convergence_messages) ||
                  length(convergence_messages) == 0) {
      ""
    } else {
      paste(as.character(convergence_messages), collapse = " | ")
    }
  )
}


# Cross-validated R2 calculated from pooled out-of-sample predictions.
# A negative value is allowed and means that predictions are worse than
# predicting the overall observed mean.
predictive_r2 <- function(observed, predicted) {
  denominator <- sum((observed - mean(observed, na.rm = TRUE))^2, na.rm = TRUE)

  if (!is.finite(denominator) || denominator <= 0) {
    return(NA_real_)
  }

  numerator <- sum((observed - predicted)^2, na.rm = TRUE)
  1 - numerator / denominator
}


# Predictive Q2 against an explicit out-of-sample reference strategy.
#
# Q2 > 0:
#   the calibrated model has a smaller squared prediction error than the
#   reference strategy.
#
# Q2 = 0:
#   the calibrated model and the reference strategy perform equally.
#
# Q2 < 0:
#   the calibrated model performs worse than the reference strategy.
#
# For the biologically most important comparison, the reference is the
# leave-one-subject-out training-subject mean.
predictive_q2 <- function(observed, predicted_model, predicted_reference) {

  valid <- is.finite(observed) &
    is.finite(predicted_model) &
    is.finite(predicted_reference)

  observed <- observed[valid]
  predicted_model <- predicted_model[valid]
  predicted_reference <- predicted_reference[valid]

  if (length(observed) == 0) {
    return(NA_real_)
  }

  model_sse <- sum((observed - predicted_model)^2, na.rm = TRUE)
  reference_sse <- sum((observed - predicted_reference)^2, na.rm = TRUE)

  if (!is.finite(reference_sse) || reference_sse <= 0) {
    return(NA_real_)
  }

  1 - model_sse / reference_sse
}


# Calculate image-weighted and subject-balanced predictive performance.
performance_metrics <- function(data, prediction_column, subject_column = "subject_id") {

  valid <- is.finite(data$observed) & is.finite(data[[prediction_column]])
  d <- data[valid, , drop = FALSE]

  if (nrow(d) == 0) {
    return(c(
      n_images = 0,
      MAE = NA_real_,
      RMSE = NA_real_,
      bias_pred_minus_obs = NA_real_,
      R2_CV_pooled = NA_real_,
      subject_balanced_MAE = NA_real_,
      subject_balanced_RMSE = NA_real_
    ))
  }

  errors <- d[[prediction_column]] - d$observed

  subject_ids <- unique(as.character(d[[subject_column]]))
  subject_mae <- numeric(length(subject_ids))
  subject_mse <- numeric(length(subject_ids))

  for (i in seq_along(subject_ids)) {
    keep <- as.character(d[[subject_column]]) == subject_ids[i]
    subject_errors <- d[[prediction_column]][keep] - d$observed[keep]
    subject_mae[i] <- mean(abs(subject_errors), na.rm = TRUE)
    subject_mse[i] <- mean(subject_errors^2, na.rm = TRUE)
  }

  c(
    n_images = nrow(d),
    MAE = mean(abs(errors), na.rm = TRUE),
    RMSE = sqrt(mean(errors^2, na.rm = TRUE)),
    bias_pred_minus_obs = mean(errors, na.rm = TRUE),
    R2_CV_pooled = predictive_r2(d$observed, d[[prediction_column]]),
    subject_balanced_MAE = mean(subject_mae, na.rm = TRUE),
    subject_balanced_RMSE = sqrt(mean(subject_mse, na.rm = TRUE))
  )
}


# Calibration of out-of-sample predictions.
# Ideal intercept = 0 and ideal slope = 1.
calibration_metrics <- function(observed, predicted) {

  valid <- is.finite(observed) & is.finite(predicted)
  observed <- observed[valid]
  predicted <- predicted[valid]

  if (length(observed) < 3 || length(unique(predicted)) < 2) {
    return(c(
      calibration_intercept = NA_real_,
      calibration_slope = NA_real_
    ))
  }

  fit <- stats::lm(observed ~ predicted)
  b <- stats::coef(fit)

  c(
    calibration_intercept = unname(b["(Intercept)"]),
    calibration_slope = unname(b["predicted"])
  )
}


# Subject-cluster bootstrap of already generated out-of-sample predictions.
# This quantifies uncertainty in predictive performance across biological
# subjects without breaking the within-subject image structure.
cluster_bootstrap_ci <- function(data, prediction_column, n_bootstrap, seed) {

  subjects <- unique(as.character(data$subject_id))

  if (length(subjects) < 2) {
    stop("Cluster bootstrap requires at least two biological subjects.", call. = FALSE)
  }

  set.seed(seed)

  one_bootstrap <- function() {

    sampled_subjects <- sample(subjects, length(subjects), replace = TRUE)
    bootstrap_parts <- vector("list", length(sampled_subjects))

    for (k in seq_along(sampled_subjects)) {
      current <- data[
        as.character(data$subject_id) == sampled_subjects[k],
        ,
        drop = FALSE
      ]

      # The same subject may be sampled repeatedly, therefore each bootstrap
      # copy receives a unique cluster identifier.
      current$bootstrap_cluster <- paste0(
        sampled_subjects[k],
        "__bootstrap_copy_",
        k
      )

      bootstrap_parts[[k]] <- current
    }

    bootstrap_data <- dplyr::bind_rows(bootstrap_parts)

    perf <- performance_metrics(
      bootstrap_data,
      prediction_column,
      subject_column = "bootstrap_cluster"
    )

    cal <- calibration_metrics(
      bootstrap_data$observed,
      bootstrap_data[[prediction_column]]
    )

    c(perf, cal)
  }

  # Determine metric names before running the bootstrap loop.
  metric_names <- names(one_bootstrap())

  bootstrap_matrix <- t(
    replicate(n_bootstrap, one_bootstrap())
  )

  bootstrap_df <- as.data.frame(bootstrap_matrix)
  names(bootstrap_df) <- metric_names

  rows <- lapply(metric_names, function(metric_name) {

    values <- bootstrap_df[[metric_name]]
    finite_values <- values[is.finite(values)]

    if (length(finite_values) == 0) {
      return(tibble::tibble(
        metric = metric_name,
        bootstrap_median = NA_real_,
        ci_95_lower = NA_real_,
        ci_95_upper = NA_real_,
        valid_bootstrap_replicates = 0L
      ))
    }

    tibble::tibble(
      metric = metric_name,
      bootstrap_median = stats::median(finite_values),
      ci_95_lower = unname(stats::quantile(finite_values, 0.025, names = FALSE)),
      ci_95_upper = unname(stats::quantile(finite_values, 0.975, names = FALSE)),
      valid_bootstrap_replicates = length(finite_values)
    )
  })

  dplyr::bind_rows(rows)
}


# Subject-cluster bootstrap for pairwise predictive Q2.
#
# This uses the already generated out-of-sample LOSO predictions and resamples
# entire biological subjects. It therefore quantifies uncertainty in the
# comparison between the calibrated model and a reference prediction strategy
# while preserving the within-subject image structure.
cluster_bootstrap_q2_ci <- function(
    data,
    model_prediction_column,
    reference_prediction_column,
    n_bootstrap,
    seed,
    metric_name
) {

  subjects <- unique(as.character(data$subject_id))

  if (length(subjects) < 2) {
    stop("Cluster bootstrap requires at least two biological subjects.", call. = FALSE)
  }

  set.seed(seed)

  bootstrap_values <- replicate(
    n_bootstrap,
    {

      sampled_subjects <- sample(
        subjects,
        length(subjects),
        replace = TRUE
      )

      bootstrap_parts <- vector(
        "list",
        length(sampled_subjects)
      )

      for (k in seq_along(sampled_subjects)) {

        current <- data[
          as.character(data$subject_id) == sampled_subjects[k],
          ,
          drop = FALSE
        ]

        current$bootstrap_cluster <- paste0(
          sampled_subjects[k],
          "__bootstrap_copy_",
          k
        )

        bootstrap_parts[[k]] <- current
      }

      bootstrap_data <- dplyr::bind_rows(
        bootstrap_parts
      )

      predictive_q2(
        observed = bootstrap_data$observed,
        predicted_model = bootstrap_data[[model_prediction_column]],
        predicted_reference = bootstrap_data[[reference_prediction_column]]
      )
    }
  )

  finite_values <- bootstrap_values[
    is.finite(bootstrap_values)
  ]

  if (length(finite_values) == 0) {
    return(
      tibble::tibble(
        metric = metric_name,
        bootstrap_median = NA_real_,
        ci_95_lower = NA_real_,
        ci_95_upper = NA_real_,
        valid_bootstrap_replicates = 0L,
        n_bootstrap_requested = n_bootstrap
      )
    )
  }

  tibble::tibble(
    metric = metric_name,
    bootstrap_median = stats::median(
      finite_values
    ),
    ci_95_lower = unname(
      stats::quantile(
        finite_values,
        0.025,
        names = FALSE
      )
    ),
    ci_95_upper = unname(
      stats::quantile(
        finite_values,
        0.975,
        names = FALSE
      )
    ),
    valid_bootstrap_replicates = length(
      finite_values
    ),
    n_bootstrap_requested = n_bootstrap
  )
}


# Fit one endpoint using LOSO-CV.
fit_loso_endpoint <- function(
    data,
    endpoint_id,
    endpoint_label,
    response_column,
    predictor_column
) {

  endpoint_data <- data |>
    dplyr::transmute(
      group,
      image_id,
      subject_id,
      disease_status,
      observed = safe_numeric(.data[[response_column]]),
      automated = safe_numeric(.data[[predictor_column]])
    ) |>
    dplyr::filter(
      is.finite(observed),
      is.finite(automated)
    )

  if (nrow(endpoint_data) < 3) {
    stop(
      paste0("Endpoint '", endpoint_id, "' contains fewer than three paired images."),
      call. = FALSE
    )
  }

  subjects <- sort(unique(as.character(endpoint_data$subject_id)))

  if (length(subjects) < 3) {
    stop(
      paste0("Endpoint '", endpoint_id, "' requires at least three subjects."),
      call. = FALSE
    )
  }

  prediction_parts <- vector("list", length(subjects))
  fold_parts <- vector("list", length(subjects))

  for (fold_index in seq_along(subjects)) {

    held_out_subject <- subjects[fold_index]

    train <- endpoint_data |>
      dplyr::filter(as.character(subject_id) != held_out_subject) |>
      dplyr::mutate(subject_id = factor(subject_id))

    test <- endpoint_data |>
      dplyr::filter(as.character(subject_id) == held_out_subject)

    if (dplyr::n_distinct(train$subject_id) < 2) {
      stop(
        paste0("Too few training subjects in fold for ", held_out_subject, "."),
        call. = FALSE
      )
    }

    if (length(unique(train$automated)) < 2) {
      stop(
        paste0("Insufficient predictor variability in fold for ", held_out_subject, "."),
        call. = FALSE
      )
    }

    fit <- tryCatch(
      lme4::lmer(
        observed ~ automated + (1 | subject_id),
        data = train,
        REML = TRUE,
        control = lme4::lmerControl(
          optimizer = "bobyqa",
          optCtrl = list(maxfun = 100000)
        )
      ),
      error = function(e) {
        stop(
          paste0(
            "Mixed model failed in LOSO fold for subject ",
            held_out_subject,
            ". Original error: ",
            conditionMessage(e)
          ),
          call. = FALSE
        )
      }
    )

    singular_fit <- lme4::isSingular(fit, tol = SINGULAR_TOL)
    convergence <- model_convergence_status(fit)
    fixed_effects <- lme4::fixef(fit)

    # Critical anti-leakage step:
    # re.form = NA removes all subject-specific random effects. Therefore the
    # held-out subject is predicted only from the population calibration line.
    predicted_calibrated <- as.numeric(
      stats::predict(
        fit,
        newdata = test,
        re.form = NA,
        allow.new.levels = TRUE
      )
    )

    # No-calibration benchmark.
    predicted_identity <- test$automated

    # Biological no-information benchmark:
    # first calculate one Manual mean per training subject, then average those
    # subject means so that every training subject has equal weight.
    training_subject_mean <- train |>
      dplyr::group_by(subject_id) |>
      dplyr::summarise(subject_mean = mean(observed), .groups = "drop") |>
      dplyr::summarise(reference_mean = mean(subject_mean)) |>
      dplyr::pull(reference_mean)

    predicted_training_subject_mean <- rep(
      training_subject_mean,
      nrow(test)
    )

    prediction_parts[[fold_index]] <- test |>
      dplyr::mutate(
        endpoint = endpoint_id,
        endpoint_label = endpoint_label,
        fold = fold_index,
        held_out_subject = held_out_subject,
        predicted_calibrated = predicted_calibrated,
        predicted_identity = predicted_identity,
        predicted_training_subject_mean = predicted_training_subject_mean,
        residual_calibrated = predicted_calibrated - observed,
        residual_identity = predicted_identity - observed,
        residual_training_subject_mean = predicted_training_subject_mean - observed
      )

    variance_table <- as.data.frame(lme4::VarCorr(fit))

    subject_sd <- variance_table$sdcor[
      variance_table$grp == "subject_id"
    ][1]

    residual_sd <- variance_table$sdcor[
      variance_table$grp == "Residual"
    ][1]

    fold_parts[[fold_index]] <- tibble::tibble(
      endpoint = endpoint_id,
      fold = fold_index,
      held_out_subject = held_out_subject,
      n_training_subjects = dplyr::n_distinct(train$subject_id),
      n_training_images = nrow(train),
      n_test_images = nrow(test),
      intercept = unname(fixed_effects["(Intercept)"]),
      slope_automated = unname(fixed_effects["automated"]),
      subject_random_intercept_sd = subject_sd,
      residual_sd = residual_sd,
      singular_fit = singular_fit,
      convergence_ok = convergence$ok,
      optimizer_code = convergence$optimizer_code,
      convergence_message = convergence$message
    )
  }

  predictions <- dplyr::bind_rows(prediction_parts)
  fold_models <- dplyr::bind_rows(fold_parts)

  # Final descriptive model fitted to all subjects.
  # Do NOT use its in-sample fit statistics as evidence of predictive ability.
  full_data <- endpoint_data |>
    dplyr::mutate(subject_id = factor(subject_id))

  full_model <- lme4::lmer(
    observed ~ automated + (1 | subject_id),
    data = full_data,
    REML = TRUE,
    control = lme4::lmerControl(
      optimizer = "bobyqa",
      optCtrl = list(maxfun = 100000)
    )
  )

  full_convergence <- model_convergence_status(full_model)

  full_fixed <- as.data.frame(summary(full_model)$coefficients) |>
    tibble::rownames_to_column("term") |>
    dplyr::rename(
      estimate = Estimate,
      std_error = `Std. Error`,
      t_value = `t value`
    ) |>
    dplyr::mutate(endpoint = endpoint_id, .before = 1)

  full_random <- as.data.frame(lme4::VarCorr(full_model)) |>
    dplyr::mutate(endpoint = endpoint_id, .before = 1)

  full_diagnostics <- full_data |>
    dplyr::mutate(
      endpoint = endpoint_id,
      fitted_full_model = as.numeric(stats::fitted(full_model)),
      residual_full_model = as.numeric(stats::residuals(full_model))
    )

  list(
    endpoint_data = endpoint_data,
    predictions = predictions,
    fold_models = fold_models,
    full_model = full_model,
    full_fixed = full_fixed,
    full_random = full_random,
    full_singular = lme4::isSingular(full_model, tol = SINGULAR_TOL),
    full_convergence_ok = full_convergence$ok,
    full_optimizer_code = full_convergence$optimizer_code,
    full_convergence_message = full_convergence$message,
    full_diagnostics = full_diagnostics
  )
}


# Calculate performance for all prediction strategies.
make_overall_performance <- function(predictions) {

  strategy_map <- c(
    calibrated_lmm = "predicted_calibrated",
    automated_identity = "predicted_identity",
    training_subject_mean = "predicted_training_subject_mean"
  )

  rows <- lapply(names(strategy_map), function(strategy_name) {

    prediction_column <- strategy_map[[strategy_name]]

    perf <- performance_metrics(
      predictions,
      prediction_column,
      subject_column = "subject_id"
    )

    cal <- calibration_metrics(
      predictions$observed,
      predictions[[prediction_column]]
    )

    tibble::tibble(
      strategy = strategy_name,
      metric = c(names(perf), names(cal)),
      estimate = c(as.numeric(perf), as.numeric(cal))
    )
  })

  dplyr::bind_rows(rows)
}


# Calculate held-out performance separately for every biological subject.
make_subject_performance <- function(predictions) {

  strategy_map <- c(
    calibrated_lmm = "predicted_calibrated",
    automated_identity = "predicted_identity",
    training_subject_mean = "predicted_training_subject_mean"
  )

  subjects <- sort(unique(as.character(predictions$subject_id)))
  rows <- list()
  row_index <- 1L

  for (strategy_name in names(strategy_map)) {

    prediction_column <- strategy_map[[strategy_name]]

    for (subject_name in subjects) {

      d <- predictions |>
        dplyr::filter(as.character(subject_id) == subject_name)

      errors <- d[[prediction_column]] - d$observed

      rows[[row_index]] <- tibble::tibble(
        strategy = strategy_name,
        subject_id = subject_name,
        disease_status = as.character(d$disease_status[1]),
        n_images = nrow(d),
        MAE = mean(abs(errors), na.rm = TRUE),
        RMSE = sqrt(mean(errors^2, na.rm = TRUE)),
        bias_pred_minus_obs = mean(errors, na.rm = TRUE)
      )

      row_index <- row_index + 1L
    }
  }

  dplyr::bind_rows(rows)
}


# Bootstrap all prediction strategies for one endpoint.
make_bootstrap_table <- function(predictions, endpoint_id, n_bootstrap, base_seed) {

  strategy_map <- c(
    calibrated_lmm = "predicted_calibrated",
    automated_identity = "predicted_identity",
    training_subject_mean = "predicted_training_subject_mean"
  )

  rows <- vector("list", length(strategy_map))
  strategy_names <- names(strategy_map)

  for (i in seq_along(strategy_names)) {

    strategy_name <- strategy_names[i]

    current_ci <- cluster_bootstrap_ci(
      data = predictions,
      prediction_column = strategy_map[[strategy_name]],
      n_bootstrap = n_bootstrap,
      seed = base_seed + i
    )

    current_ci$endpoint <- endpoint_id
    current_ci$strategy <- strategy_name
    current_ci$n_bootstrap_requested <- n_bootstrap
    rows[[i]] <- current_ci
  }

  dplyr::bind_rows(rows) |>
    dplyr::select(
      endpoint,
      strategy,
      metric,
      bootstrap_median,
      ci_95_lower,
      ci_95_upper,
      valid_bootstrap_replicates,
      n_bootstrap_requested
    )
}


