# ================================================================
# PREDICTIVE VALIDATION OF AUTOMATED CRISTAE QUANTIFICATION
# ================================================================
#
# Scientific question
# -------------------
# Can automated cristae quantification predict the corresponding manual
# reference measurement in a previously unseen biological subject?
#
# This workflow is a PREDICTIVE validation analysis. It is intentionally
# separate from the inferential Ctrl-vs-HD analyses already present in the
# repository. Disease status is retained only as metadata for plotting and
# is never used as a predictor.
#
# Input
# -----
# results/derived/Prism_input.xlsx
# worksheet: compare_images
#
# The input is generated by:
#   Rscript scripts/R/prepare_prism_input.R
#
# Primary endpoint
# ----------------
# manual_mean_per_mito ~ auto_mean_per_mito
#
# `mean_per_mito` is the image-level pooled cristae rate:
#   total cristae in image / number of mitochondria in image
#
# Secondary endpoint
# ------------------
# manual_total ~ auto_total
#
# Total cristae per image is retained as a secondary endpoint for continuity
# with the existing total-cristae and Bland-Altman workflows. Because total
# counts depend on the number of mitochondria present in an image, the rate-
# based primary endpoint is the preferred biological endpoint.
#
# Calibration model
# -----------------
#   Manual_ij = beta_0 + beta_1 * Automated_ij + u_i + epsilon_ij
#
#   i = biological subject
#   j = image
#   u_i = subject-specific random intercept
#
# The random intercept accounts for repeated images from the same biological
# subject while estimating the calibration relationship.
#
# Validation design
# -----------------
# Leave-one-subject-out cross-validation (LOSO-CV):
#
#   1. hold out ALL images from one biological subject;
#   2. fit the model to the remaining subjects;
#   3. predict the held-out subject using FIXED EFFECTS ONLY;
#   4. repeat until every subject has served as the held-out test subject.
#
# This prevents subject-level data leakage. Random effects estimated for the
# training subjects are never transferred to the held-out subject.
#
# Prediction strategies compared
# ------------------------------
# 1. calibrated_lmm
#      LOSO prediction from the mixed-effects calibration model.
#
# 2. automated_identity
#      predicted Manual = observed Automated
#      This tests whether statistical calibration improves on simply treating
#      the automated measurement as equivalent to the manual measurement.
#
# 3. training_subject_mean
#      predicted Manual = mean of the subject-specific Manual means in the
#      training set. Each training subject contributes equal weight.
#      This is the no-information biological baseline.
#
# Performance metrics
# -------------------
# Image-weighted:
#   MAE                  lower is better
#   RMSE                 lower is better
#   bias                 ideal = 0
#   pooled CV R2         higher is better; may be negative
#
# Subject-balanced:
#   subject_balanced_MAE
#   subject_balanced_RMSE
#
# Calibration of out-of-sample predictions:
#   calibration intercept   ideal = 0
#   calibration slope       ideal = 1
#
# Pairwise predictive value:
#   Q2_vs_training_subject_mean
#      > 0  calibrated model outperforms the biological no-information baseline
#      = 0  equal squared prediction error
#      < 0  calibrated model performs worse than the baseline
#
#   Q2_vs_automated_identity
#      > 0  statistical calibration improves on using Automated as-is
#
# Uncertainty
# -----------
# 95% confidence intervals are estimated by subject-cluster bootstrap of the
# already generated LOSO out-of-sample predictions. Entire held-out biological
# subjects are resampled, preserving within-subject dependence.
#
# IMPORTANT
# ---------
# Predictive performance must be interpreted from LOSO out-of-sample
# predictions. The model fitted to the complete dataset is exported only to
# describe the final calibration equation and inspect model diagnostics.
#
# Run from repository root:
#   Rscript scripts/R/cristae_prediction_validation.R
# ================================================================


