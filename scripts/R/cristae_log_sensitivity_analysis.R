# ----------------------------------------------------------------
# STEP 7: Run LOSO log-transformed sensitivity models
# ----------------------------------------------------------------

announce_step(
  7,
  "Run LOSO log-transformed sensitivity models"
)

all_predictions <- list()
all_fold_models <- list()
full_model_diagnostics <- list()
full_model_status <- list()

for (endpoint_index in seq_len(nrow(endpoint_definitions))) {

  endpoint_id <- endpoint_definitions$endpoint[
    endpoint_index
  ]

  response_column <- endpoint_definitions$manual_response[
    endpoint_index
  ]

  predictor_column <- endpoint_definitions$automated_predictor[
    endpoint_index
  ]

  cat(
    "\nRunning endpoint: ",
    endpoint_id,
    "\n",
    sep = ""
  )

  endpoint_data <- analysis_data |>
    dplyr::transmute(
      group,
      image_id,
      subject_id,
      disease_status,
      observed = safe_numeric(
        .data[[response_column]]
      ),
      automated = safe_numeric(
        .data[[predictor_column]]
      )
    ) |>
    dplyr::filter(
      is.finite(observed),
      is.finite(automated)
    )

  if (
    any(endpoint_data$observed < 0) ||
      any(endpoint_data$automated < 0)
  ) {
    stop(
      paste0(
        "Endpoint ",
        endpoint_id,
        " contains negative values and cannot be analyzed with log1p."
      ),
      call. = FALSE
    )
  }

  endpoint_data <- endpoint_data |>
    dplyr::mutate(
      log_observed = log1p(
        observed
      ),
      log_automated = log1p(
        automated
      )
    )

  if (nrow(endpoint_data) < 3) {
    stop(
      paste0(
        "Endpoint '",
        endpoint_id,
        "' contains fewer than three paired images."
      ),
      call. = FALSE
    )
  }

  subjects <- sort(
    unique(
      as.character(
        endpoint_data$subject_id
      )
    )
  )

  if (length(subjects) < 3) {
    stop(
      paste0(
        "Endpoint '",
        endpoint_id,
        "' requires at least three biological subjects."
      ),
      call. = FALSE
    )
  }

  prediction_parts <- vector(
    "list",
    length(subjects)
  )

  fold_parts <- vector(
    "list",
    length(subjects)
  )

  for (fold_index in seq_along(subjects)) {

    held_out_subject <- subjects[
      fold_index
    ]

    train <- endpoint_data |>
      dplyr::filter(
        as.character(subject_id) !=
          held_out_subject
      ) |>
      dplyr::mutate(
        subject_id = factor(
          subject_id
        )
      )

    test <- endpoint_data |>
      dplyr::filter(
        as.character(subject_id) ==
          held_out_subject
      )

    if (dplyr::n_distinct(train$subject_id) < 2) {
      stop(
        paste0(
          "Too few training subjects in LOSO fold for ",
          held_out_subject,
          "."
        ),
        call. = FALSE
      )
    }

    if (length(unique(train$log_automated)) < 2) {
      stop(
        paste0(
          "Insufficient predictor variability in LOSO fold for ",
          held_out_subject,
          "."
        ),
        call. = FALSE
      )
    }

    fit <- tryCatch(
      lme4::lmer(
        log_observed ~
          log_automated +
          (1 | subject_id),
        data = train,
        REML = TRUE,
        control = lme4::lmerControl(
          optimizer = "bobyqa",
          optCtrl = list(
            maxfun = 100000
          )
        )
      ),
      error = function(e) {
        stop(
          paste0(
            "Log-scale mixed model failed in LOSO fold for subject ",
            held_out_subject,
            ". Original error: ",
            conditionMessage(e)
          ),
          call. = FALSE
        )
      }
    )

    convergence <- model_convergence_status(
      fit
    )

    singular_fit <- lme4::isSingular(
      fit,
      tol = SINGULAR_TOL
    )

    # Population-level log predictions for training data.
    # These are used to estimate the fold-specific Duan smearing factor.
    train_log_prediction_population <- as.numeric(
      stats::predict(
        fit,
        newdata = train,
        re.form = NA,
        allow.new.levels = TRUE
      )
    )

    population_log_residual <- (
      train$log_observed -
        train_log_prediction_population
    )

    smearing_factor <- mean(
      exp(
        population_log_residual
      ),
      na.rm = TRUE
    )

    if (!is.finite(smearing_factor) || smearing_factor <= 0) {
      stop(
        paste0(
          "Invalid Duan smearing factor in LOSO fold for subject ",
          held_out_subject,
          "."
        ),
        call. = FALSE
      )
    }

    # Predict the held-out subject using fixed effects only.
    predicted_log <- as.numeric(
      stats::predict(
        fit,
        newdata = test,
        re.form = NA,
        allow.new.levels = TRUE
      )
    )

    # Naive retransformation is retained only as a diagnostic.
    predicted_naive_backtransform <- expm1(
      predicted_log
    )

    # Main sensitivity prediction on the original scale.
    # log1p(Y) is predicted; therefore:
    #   Y + 1 = exp(predicted_log) * smearing_factor
    #   Y     = exp(predicted_log) * smearing_factor - 1
    predicted_log_sensitivity <- (
      exp(
        predicted_log
      ) *
        smearing_factor -
        1
    )

    # Baseline 1: Automated value without statistical calibration.
    predicted_identity <- test$automated

    # Baseline 2: equal-weight average of training-subject Manual means.
    training_subject_mean <- train |>
      dplyr::group_by(
        subject_id
      ) |>
      dplyr::summarise(
        subject_mean = mean(
          observed
        ),
        .groups = "drop"
      ) |>
      dplyr::summarise(
        reference_mean = mean(
          subject_mean
        )
      ) |>
      dplyr::pull(
        reference_mean
      )

    predicted_training_subject_mean <- rep(
      training_subject_mean,
      nrow(test)
    )

    prediction_parts[[fold_index]] <- test |>
      dplyr::mutate(
        endpoint = endpoint_id,
        fold = fold_index,
        held_out_subject = held_out_subject,
        smearing_factor = smearing_factor,
        predicted_log_scale = predicted_log,
        predicted_naive_backtransform =
          predicted_naive_backtransform,
        predicted_log_sensitivity =
          predicted_log_sensitivity,
        predicted_identity =
          predicted_identity,
        predicted_training_subject_mean =
          predicted_training_subject_mean,
        negative_backtransformed_prediction =
          predicted_log_sensitivity < 0,
        residual_log_sensitivity =
          predicted_log_sensitivity -
          observed
      )

    variance_table <- as.data.frame(
      lme4::VarCorr(
        fit
      )
    )

    fixed_effects <- lme4::fixef(
      fit
    )

    fold_parts[[fold_index]] <- tibble::tibble(
      endpoint = endpoint_id,
      fold = fold_index,
      held_out_subject = held_out_subject,
      n_training_subjects =
        dplyr::n_distinct(
          train$subject_id
        ),
      n_training_images =
        nrow(train),
      n_test_images =
        nrow(test),
      intercept_log_scale =
        unname(
          fixed_effects["(Intercept)"]
        ),
      slope_log_automated =
        unname(
          fixed_effects["log_automated"]
        ),
      smearing_factor =
        smearing_factor,
      subject_random_intercept_sd =
        variance_table$sdcor[
          variance_table$grp ==
            "subject_id"
        ][1],
      residual_sd =
        variance_table$sdcor[
          variance_table$grp ==
            "Residual"
        ][1],
      singular_fit =
        singular_fit,
      convergence_ok =
        convergence$ok,
      optimizer_code =
        convergence$optimizer_code,
      convergence_message =
        convergence$message
    )
  }

  endpoint_predictions <- dplyr::bind_rows(
    prediction_parts
  )

  endpoint_fold_models <- dplyr::bind_rows(
    fold_parts
  )

  all_predictions[[endpoint_id]] <-
    endpoint_predictions

  all_fold_models[[endpoint_id]] <-
    endpoint_fold_models

  # Full-data log model for diagnostic inspection only.
  full_data <- endpoint_data |>
    dplyr::mutate(
      subject_id = factor(
        subject_id
      )
    )

  full_fit <- lme4::lmer(
    log_observed ~
      log_automated +
      (1 | subject_id),
    data = full_data,
    REML = TRUE,
    control = lme4::lmerControl(
      optimizer = "bobyqa",
      optCtrl = list(
        maxfun = 100000
      )
    )
  )

  full_convergence <- model_convergence_status(
    full_fit
  )

  full_model_status[[endpoint_id]] <-
    tibble::tibble(
      endpoint = endpoint_id,
      singular_fit =
        lme4::isSingular(
          full_fit,
          tol = SINGULAR_TOL
        ),
      convergence_ok =
        full_convergence$ok,
      optimizer_code =
        full_convergence$optimizer_code,
      convergence_message =
        full_convergence$message
    )

  full_model_diagnostics[[endpoint_id]] <-
    full_data |>
    dplyr::mutate(
      endpoint = endpoint_id,
      fitted_log_scale =
        as.numeric(
          stats::fitted(
            full_fit
          )
        ),
      residual_log_scale =
        as.numeric(
          stats::residuals(
            full_fit
          )
        )
    )
}

