# ----------------------------------------------------------------
# STEP 8: Calculate predictive performance on the original scale
# ----------------------------------------------------------------

announce_step(
  8,
  "Calculate out-of-sample predictive performance"
)

strategy_map <- c(
  log_sensitivity =
    "predicted_log_sensitivity",
  automated_identity =
    "predicted_identity",
  training_subject_mean =
    "predicted_training_subject_mean"
)

overall_parts <- list()
subject_parts <- list()
q2_parts <- list()

for (endpoint_id in endpoint_definitions$endpoint) {

  d <- predictions |>
    dplyr::filter(
      endpoint == endpoint_id
    )

  endpoint_overall <- list()
  endpoint_subject <- list()

  for (strategy_name in names(strategy_map)) {

    prediction_column <-
      strategy_map[[strategy_name]]

    perf <- performance_metrics(
      d,
      prediction_column,
      subject_column = "subject_id"
    )

    # Calibration is meaningful for actual measurement-based predictions.
    # It is intentionally not interpreted for the training-subject-mean
    # no-information baseline.
    if (
      strategy_name ==
        "training_subject_mean"
    ) {
      cal <- c(
        calibration_intercept =
          NA_real_,
        calibration_slope =
          NA_real_
      )
    } else {
      cal <- calibration_metrics(
        d$observed,
        d[[prediction_column]]
      )
    }

    endpoint_overall[[strategy_name]] <-
      tibble::tibble(
        endpoint = endpoint_id,
        strategy = strategy_name,
        metric = c(
          names(perf),
          names(cal)
        ),
        estimate = c(
          as.numeric(perf),
          as.numeric(cal)
        )
      )

    subjects <- sort(
      unique(
        as.character(
          d$subject_id
        )
      )
    )

    subject_rows <- lapply(
      subjects,
      function(subject_name) {

        sd <- d |>
          dplyr::filter(
            as.character(subject_id) ==
              subject_name
          )

        errors <- (
          sd[[prediction_column]] -
            sd$observed
        )

        tibble::tibble(
          endpoint = endpoint_id,
          strategy = strategy_name,
          subject_id = subject_name,
          disease_status =
            as.character(
              sd$disease_status[1]
            ),
          n_images =
            nrow(sd),
          MAE =
            mean(
              abs(errors)
            ),
          RMSE =
            sqrt(
              mean(
                errors^2
              )
            ),
          bias_pred_minus_obs =
            mean(
              errors
            )
        )
      }
    )

    endpoint_subject[[strategy_name]] <-
      dplyr::bind_rows(
        subject_rows
      )
  }

  overall_parts[[endpoint_id]] <-
    dplyr::bind_rows(
      endpoint_overall
    )

  subject_parts[[endpoint_id]] <-
    dplyr::bind_rows(
      endpoint_subject
    )

  q2_parts[[endpoint_id]] <-
    tibble::tibble(
      endpoint = endpoint_id,
      metric = c(
        "Q2_vs_automated_identity",
        "Q2_vs_training_subject_mean"
      ),
      estimate = c(
        predictive_q2(
          d$observed,
          d$predicted_log_sensitivity,
          d$predicted_identity
        ),
        predictive_q2(
          d$observed,
          d$predicted_log_sensitivity,
          d$predicted_training_subject_mean
        )
      )
    )
}

