safe_numeric <- function(x) {
  suppressWarnings(as.numeric(x))
}


model_convergence_status <- function(model) {

  optimizer_code <- model@optinfo$conv$opt
  convergence_messages <- model@optinfo$conv$lme4$messages

  optimizer_ok <- is.null(optimizer_code) ||
    all(unlist(optimizer_code, use.names = FALSE) == 0)

  messages_ok <- is.null(convergence_messages) ||
    length(convergence_messages) == 0

  list(
    ok = isTRUE(optimizer_ok) && isTRUE(messages_ok),
    optimizer_code = if (is.null(optimizer_code)) {
      NA_character_
    } else {
      paste(
        as.character(
          unlist(
            optimizer_code,
            use.names = FALSE
          )
        ),
        collapse = "; "
      )
    },
    message = if (
      is.null(convergence_messages) ||
        length(convergence_messages) == 0
    ) {
      ""
    } else {
      paste(
        as.character(convergence_messages),
        collapse = " | "
      )
    }
  )
}


predictive_r2 <- function(observed, predicted) {

  valid <- is.finite(observed) & is.finite(predicted)
  observed <- observed[valid]
  predicted <- predicted[valid]

  if (length(observed) == 0) {
    return(NA_real_)
  }

  denominator <- sum(
    (observed - mean(observed))^2
  )

  if (!is.finite(denominator) || denominator <= 0) {
    return(NA_real_)
  }

  numerator <- sum(
    (observed - predicted)^2
  )

  1 - numerator / denominator
}


predictive_q2 <- function(
    observed,
    predicted_model,
    predicted_reference
) {

  valid <- is.finite(observed) &
    is.finite(predicted_model) &
    is.finite(predicted_reference)

  observed <- observed[valid]
  predicted_model <- predicted_model[valid]
  predicted_reference <- predicted_reference[valid]

  if (length(observed) == 0) {
    return(NA_real_)
  }

  model_sse <- sum(
    (observed - predicted_model)^2
  )

  reference_sse <- sum(
    (observed - predicted_reference)^2
  )

  if (!is.finite(reference_sse) || reference_sse <= 0) {
    return(NA_real_)
  }

  1 - model_sse / reference_sse
}


performance_metrics <- function(
    data,
    prediction_column,
    subject_column = "subject_id"
) {

  valid <- is.finite(data$observed) &
    is.finite(data[[prediction_column]])

  d <- data[
    valid,
    ,
    drop = FALSE
  ]

  if (nrow(d) == 0) {
    return(
      c(
        n_images = 0,
        MAE = NA_real_,
        RMSE = NA_real_,
        bias_pred_minus_obs = NA_real_,
        R2_CV_pooled = NA_real_,
        subject_balanced_MAE = NA_real_,
        subject_balanced_RMSE = NA_real_
      )
    )
  }

  errors <- d[[prediction_column]] - d$observed

  subject_ids <- unique(
    as.character(
      d[[subject_column]]
    )
  )

  subject_mae <- numeric(
    length(subject_ids)
  )

  subject_mse <- numeric(
    length(subject_ids)
  )

  for (i in seq_along(subject_ids)) {

    keep <- as.character(
      d[[subject_column]]
    ) == subject_ids[i]

    subject_errors <- (
      d[[prediction_column]][keep] -
        d$observed[keep]
    )

    subject_mae[i] <- mean(
      abs(subject_errors)
    )

    subject_mse[i] <- mean(
      subject_errors^2
    )
  }

  c(
    n_images = nrow(d),
    MAE = mean(
      abs(errors)
    ),
    RMSE = sqrt(
      mean(
        errors^2
      )
    ),
    bias_pred_minus_obs = mean(
      errors
    ),
    R2_CV_pooled = predictive_r2(
      d$observed,
      d[[prediction_column]]
    ),
    subject_balanced_MAE = mean(
      subject_mae
    ),
    subject_balanced_RMSE = sqrt(
      mean(
        subject_mse
      )
    )
  )
}


calibration_metrics <- function(
    observed,
    predicted
) {

  valid <- is.finite(observed) &
    is.finite(predicted)

  observed <- observed[valid]
  predicted <- predicted[valid]

  if (
    length(observed) < 3 ||
      length(unique(predicted)) < 2
  ) {
    return(
      c(
        calibration_intercept = NA_real_,
        calibration_slope = NA_real_
      )
    )
  }

  fit <- stats::lm(
    observed ~ predicted
  )

  b <- stats::coef(
    fit
  )

  c(
    calibration_intercept = unname(
      b["(Intercept)"]
    ),
    calibration_slope = unname(
      b["predicted"]
    )
  )
}


cluster_bootstrap_metrics <- function(
    data,
    prediction_column,
    n_bootstrap,
    seed
) {

  subjects <- unique(
    as.character(
      data$subject_id
    )
  )

  if (length(subjects) < 2) {
    stop(
      "Cluster bootstrap requires at least two biological subjects.",
      call. = FALSE
    )
  }

  set.seed(seed)

  one_bootstrap <- function() {

    sampled_subjects <- sample(
      subjects,
      length(subjects),
      replace = TRUE
    )

    parts <- vector(
      "list",
      length(sampled_subjects)
    )

    for (k in seq_along(sampled_subjects)) {

      current <- data[
        as.character(data$subject_id) ==
          sampled_subjects[k],
        ,
        drop = FALSE
      ]

      current$bootstrap_cluster <- paste0(
        sampled_subjects[k],
        "__copy_",
        k
      )

      parts[[k]] <- current
    }

    bootstrap_data <- dplyr::bind_rows(
      parts
    )

    perf <- performance_metrics(
      bootstrap_data,
      prediction_column,
      subject_column = "bootstrap_cluster"
    )

    cal <- calibration_metrics(
      bootstrap_data$observed,
      bootstrap_data[[prediction_column]]
    )

    c(
      perf,
      cal
    )
  }

  metric_names <- names(
    one_bootstrap()
  )

  bootstrap_matrix <- t(
    replicate(
      n_bootstrap,
      one_bootstrap()
    )
  )

  bootstrap_df <- as.data.frame(
    bootstrap_matrix
  )

  names(bootstrap_df) <- metric_names

  rows <- lapply(
    metric_names,
    function(metric_name) {

      values <- bootstrap_df[[metric_name]]
      values <- values[
        is.finite(values)
      ]

      if (length(values) == 0) {
        return(
          tibble::tibble(
            metric = metric_name,
            bootstrap_median = NA_real_,
            ci_95_lower = NA_real_,
            ci_95_upper = NA_real_,
            valid_bootstrap_replicates = 0L,
            n_bootstrap_requested = n_bootstrap
          )
        )
      }

      tibble::tibble(
        metric = metric_name,
        bootstrap_median = stats::median(
          values
        ),
        ci_95_lower = unname(
          stats::quantile(
            values,
            0.025,
            names = FALSE
          )
        ),
        ci_95_upper = unname(
          stats::quantile(
            values,
            0.975,
            names = FALSE
          )
        ),
        valid_bootstrap_replicates = length(
          values
        ),
        n_bootstrap_requested = n_bootstrap
      )
    }
  )

  dplyr::bind_rows(
    rows
  )
}


cluster_bootstrap_q2 <- function(
    data,
    model_prediction_column,
    reference_prediction_column,
    n_bootstrap,
    seed,
    metric_name
) {

  subjects <- unique(
    as.character(
      data$subject_id
    )
  )

  if (length(subjects) < 2) {
    stop(
      "Cluster bootstrap requires at least two biological subjects.",
      call. = FALSE
    )
  }

  set.seed(seed)

  bootstrap_values <- replicate(
    n_bootstrap,
    {

      sampled_subjects <- sample(
        subjects,
        length(subjects),
        replace = TRUE
      )

      parts <- vector(
        "list",
        length(sampled_subjects)
      )

      for (k in seq_along(sampled_subjects)) {

        current <- data[
          as.character(data$subject_id) ==
            sampled_subjects[k],
          ,
          drop = FALSE
        ]

        parts[[k]] <- current
      }

      bootstrap_data <- dplyr::bind_rows(
        parts
      )

      predictive_q2(
        observed = bootstrap_data$observed,
        predicted_model =
          bootstrap_data[[model_prediction_column]],
        predicted_reference =
          bootstrap_data[[reference_prediction_column]]
      )
    }
  )

  values <- bootstrap_values[
    is.finite(bootstrap_values)
  ]

  if (length(values) == 0) {
    return(
      tibble::tibble(
        metric = metric_name,
        bootstrap_median = NA_real_,
        ci_95_lower = NA_real_,
        ci_95_upper = NA_real_,
        valid_bootstrap_replicates = 0L,
        n_bootstrap_requested = n_bootstrap
      )
    )
  }

  tibble::tibble(
    metric = metric_name,
    bootstrap_median = stats::median(
      values
    ),
    ci_95_lower = unname(
      stats::quantile(
        values,
        0.025,
        names = FALSE
      )
    ),
    ci_95_upper = unname(
      stats::quantile(
        values,
        0.975,
        names = FALSE
      )
    ),
    valid_bootstrap_replicates = length(
      values
    ),
    n_bootstrap_requested = n_bootstrap
  )
}


