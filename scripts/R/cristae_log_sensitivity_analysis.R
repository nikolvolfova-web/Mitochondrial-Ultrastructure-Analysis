# STEP 9: Subject-cluster bootstrap 95% confidence intervals
# ----------------------------------------------------------------

announce_step(
  9,
  "Calculate subject-cluster bootstrap confidence intervals"
)

bootstrap_metric_parts <- list()
bootstrap_q2_parts <- list()

for (endpoint_index in seq_len(nrow(endpoint_definitions))) {

  endpoint_id <- endpoint_definitions$endpoint[
    endpoint_index
  ]

  d <- predictions |>
    dplyr::filter(
      endpoint == endpoint_id
    )

  current_metric_rows <- list()

  for (strategy_index in seq_along(strategy_map)) {

    strategy_name <- names(
      strategy_map
    )[strategy_index]

    prediction_column <-
      strategy_map[[strategy_name]]

    current_ci <-
      cluster_bootstrap_metrics(
        data = d,
        prediction_column =
          prediction_column,
        n_bootstrap =
          N_BOOTSTRAP,
        seed =
          RANDOM_SEED +
          endpoint_index * 1000L +
          strategy_index
      ) |>
      dplyr::mutate(
        endpoint =
          endpoint_id,
        strategy =
          strategy_name,
        .before = 1
      )

    # Calibration of the no-information baseline is not interpreted.
    if (
      strategy_name ==
        "training_subject_mean"
    ) {
      current_ci <- current_ci |>
        dplyr::mutate(
          bootstrap_median =
            ifelse(
              metric %in%
                c(
                  "calibration_intercept",
                  "calibration_slope"
                ),
              NA_real_,
              bootstrap_median
            ),
          ci_95_lower =
            ifelse(
              metric %in%
                c(
                  "calibration_intercept",
                  "calibration_slope"
                ),
              NA_real_,
              ci_95_lower
            ),
          ci_95_upper =
            ifelse(
              metric %in%
                c(
                  "calibration_intercept",
                  "calibration_slope"
                ),
              NA_real_,
              ci_95_upper
            )
        )
    }

    current_metric_rows[[strategy_name]] <-
      current_ci
  }

  bootstrap_metric_parts[[endpoint_id]] <-
    dplyr::bind_rows(
      current_metric_rows
    )

  q2_identity <- cluster_bootstrap_q2(
    data = d,
    model_prediction_column =
      "predicted_log_sensitivity",
    reference_prediction_column =
      "predicted_identity",
    n_bootstrap =
      N_BOOTSTRAP,
    seed =
      RANDOM_SEED +
      5000L +
      endpoint_index,
    metric_name =
      "Q2_vs_automated_identity"
  )

  q2_training_mean <- cluster_bootstrap_q2(
    data = d,
    model_prediction_column =
      "predicted_log_sensitivity",
    reference_prediction_column =
      "predicted_training_subject_mean",
    n_bootstrap =
      N_BOOTSTRAP,
    seed =
      RANDOM_SEED +
      6000L +
      endpoint_index,
    metric_name =
      "Q2_vs_training_subject_mean"
  )

  bootstrap_q2_parts[[endpoint_id]] <-
    dplyr::bind_rows(
      q2_identity,
      q2_training_mean
    ) |>
    dplyr::mutate(
      endpoint = endpoint_id,
      .before = 1
    )
}

bootstrap_95CI <- dplyr::bind_rows(
  bootstrap_metric_parts
)

q2_bootstrap_95CI <- dplyr::bind_rows(
  bootstrap_q2_parts
)


