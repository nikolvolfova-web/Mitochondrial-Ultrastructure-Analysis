# ================================================================
# LOG-TRANSFORMED SENSITIVITY ANALYSIS
# Predictive validation of Automated vs Manual cristae measurements
# ================================================================
#
# Purpose
# -------
# This script is a sensitivity analysis for the main predictive workflow.
# It evaluates whether the main predictive conclusion remains similar after
# reducing the influence of very large values and heteroscedasticity by using
# a log1p transformation.
#
# Scientific question
# -------------------
# Does the predictive relationship between Automated and Manual measurements
# remain robust when the calibration model is fitted on the log-transformed
# scale?
#
# Validation design
# -----------------
# Leave-one-subject-out cross-validation (LOSO-CV):
#
#   1. hold out all images from one biological subject;
#   2. fit the model using all remaining subjects;
#   3. predict the held-out subject using fixed effects only;
#   4. repeat until every subject has been held out once.
#
# This preserves the biological hierarchy and prevents subject-level leakage.
#
# Log-scale model
# ---------------
#   log1p(Manual_ij) =
#       beta_0 + beta_1 * log1p(Automated_ij) + u_i + epsilon_ij
#
# where:
#   i = biological subject
#   j = image
#   u_i = subject-specific random intercept
#
# Back-transformation
# -------------------
# Predictions are returned to the original measurement scale.
#
# A Duan smearing correction is estimated independently inside every training
# fold using population-level training residuals. This reduces retransformation
# bias when converting log-scale predictions back to the original scale.
#
# Primary endpoint
# ----------------
# manual_mean_per_mito predicted from auto_mean_per_mito
#
# Secondary endpoint
# ------------------
# manual_total predicted from auto_total
#
# Benchmarks
# ----------
# 1. Automated identity:
#      predicted Manual = Automated
#
# 2. Training subject mean:
#      mean of subject-specific Manual means among the training subjects
#
# Run from repository root
# ------------------------
#   Rscript scripts/R/cristae_log_sensitivity_analysis.R
#
# The required Prism_input.xlsx file is generated by:
#   Rscript scripts/R/prepare_prism_input.R
#
# IMPORTANT
# ---------
# This script is a sensitivity analysis only.
# The primary predictive analysis remains the original-scale LOSO model.
# The purpose of this script is to assess robustness of the primary conclusion
# to log1p transformation and retransformation of predictions.
#
# Main outputs
# ------------
# - out-of-sample LOSO predictions
# - MAE, RMSE, bias, pooled CV R2
# - subject-balanced MAE and RMSE
# - predictive Q2 versus both benchmarks
# - calibration intercept and slope
# - subject-cluster bootstrap 95% confidence intervals
# - diagnostic figures
#
# ================================================================


